public class SamAveragePCM {

    public static void main(String[] args) {

        // Given marks
        int maths = 94;
        int physics = 95;
        int chemistry = 96;

        // Calculate average percentage
        double average = (maths + physics + chemistry) / 3.0;

        // Display result
        System.out.println("Sam’s average mark in PCM is " + average);
    }
}